export function getNewsBySector(sectorId: string, limit?: number): NewsItem[] {
  const filtered = NEWS.filter((n) => n.sectorIds.includes(sectorId as any)).sort(
    (a, b) => +new Date(b.publishedAt) - +new Date(a.publishedAt),
  );
  return typeof limit === "number" ? filtered.slice(0, limit) : filtered;
}

export function getLatestNews(limit = 12): NewsItem[] {
  return [...NEWS]
    .sort((a, b) => +new Date(b.publishedAt) - +new Date(a.publishedAt))
    .slice(0, limit);
}
